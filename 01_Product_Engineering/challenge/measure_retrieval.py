"""Score every retrieval technique against the labelled questions.

    uv run python measure_retrieval.py            # all techniques, every question once
    uv run python measure_retrieval.py --only q03 # one question, for debugging

Writes the results table (metrics and settings only) to
use_case/evals/retrieval_results.md, and the full traces, which contain
synthetic ticket text, to use_case/data/ (gitignored).
"""

import argparse
import json
import statistics
import time
from datetime import datetime
from pathlib import Path

import corpus
import retrieval

ROOT = Path(__file__).resolve().parent.parent.parent
LABELS = ROOT / "use_case" / "evals" / "retrieval.jsonl"
RESULTS = ROOT / "use_case" / "evals" / "retrieval_results.md"
TRACES = ROOT / "use_case" / "data" / "retrieval_traces.jsonl"
EMBED_CACHE = ROOT / "use_case" / "data" / ".embed_cache"

# Session 5 scored a refusal by markers like "not " and "no ", which almost any
# answer contains. The answer model now declines with an explicit prefix, so the
# scorer checks for that instead: a pass on a decline question is that prefix
# with no forbidden term, and an answer that declines can never pass.

def normalise(text: str) -> str:
    # "needs_information" in a page and "needs information" in an answer are the same fact.
    return (text or "").lower().replace("_", " ")


def has_term(answer: str, term: str | list[str]) -> bool:
    """A term is a phrase, or a list of acceptable phrasings of the same fact."""
    options = term if isinstance(term, list) else [term]
    return any(normalise(option) in answer for option in options)


def score(case: dict, result: dict, retriever: retrieval.Retriever) -> dict:
    answer = normalise(result["answer"])
    cited = retrieval.cited_pages(result["answer"], retriever)
    declined = retrieval.decline_reason(result["answer"]) is not None
    if case.get("must_decline"):
        passed = declined and not any(has_term(answer, term) for term in case["expected_terms"])
        cited_ok = None  # nothing should be cited; not counted in the citation rate
    else:
        passed = not declined and bool(answer) and all(has_term(answer, term) for term in case["expected_terms"])
        # Stricter than Session 5's "any expected page": a two-record question
        # answered from one record is the model guessing from the nearest chunk.
        cited_ok = set(case["gold"]) <= set(cited)
    return {"pass": passed, "declined": declined, "cited": cited_ok, "cited_pages": cited, "calls": result["calls"],
            "evidence_chars": result["evidence_chars"], "tokens": result["tokens"],
            "latency_s": result["latency_s"], "stopped": result["stopped"]}


def summarise(rows: list[dict], techniques: list[str]) -> list[dict]:
    table = []
    for technique in techniques:
        mine = [row for row in rows if row["technique"] == technique]
        cited = [row["cited"] for row in mine if row["cited"] is not None]
        table.append({
            "technique": technique,
            "pass": f"{sum(row['pass'] for row in mine)}/{len(mine)}",
            "cited": f"{sum(cited)}/{len(cited)}",
            "calls": round(statistics.mean(row["calls"] for row in mine), 1),
            "evidence": round(statistics.mean(row["evidence_chars"] for row in mine)),
            "tokens": round(statistics.mean(row["tokens"] for row in mine)),
            "latency": round(statistics.median(row["latency_s"] for row in mine), 1),
            "max_turns": sum(row["stopped"] == "max_turns" for row in mine),
        })
    return table


def write_report(table, rows, cases, similarities, retriever, started, techniques) -> None:
    header = "| Technique | Pass | Cited every gold | Avg calls | Avg evidence (chars) | Avg tokens | Median latency (s) | Hit turn limit |"
    lines = [
        "# Retrieval results (TC3 Step 3)",
        "",
        f"Run {started:%Y-%m-%d %H:%M}, {len(cases)} questions × {len(techniques)} techniques, one run each. "
        "Generated by `01_Product_Engineering/challenge/measure_retrieval.py`; traces stay in `use_case/data/`.",
        "",
        header,
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    lines += [f"| `{r['technique']}` | {r['pass']} | {r['cited']} | {r['calls']} | {r['evidence']:,} | "
              f"{r['tokens']:,} | {r['latency']} | {r['max_turns']} |" for r in table]
    lines += ["", "Citation is counted over the questions with gold records (decline questions have none).", "",
              "## Per question", "",
              "| Question | Kind | Top cosine | " + " | ".join(f"`{t}`" for t in techniques) + " |",
              "| --- | --- | --- | " + " | ".join("---" for _ in techniques) + " |"]
    for case in cases:
        cells = []
        for technique in techniques:
            row = next(r for r in rows if r["id"] == case["id"] and r["technique"] == technique)
            mark = ("pass" if row["pass"] else "FAIL") + ("" if row["cited"] in (None, True) else ", miscited")
            cells.append(f"{mark} ({row['calls']} calls)")
        cosine = similarities[case["id"]]
        lines.append(f"| {case['id']} | {case['kind']} | {'n/a' if cosine is None else f'{cosine:.3f}'} | "
                     + " | ".join(cells) + " |")
    lines += ["", "## Settings", "",
              f"- **Answer model:** `{retrieval.CHAT_MODEL}`, provider-default sampling",
              f"- **Turn budget:** {retrieval.MAX_TURNS} (agentic techniques); the pipeline makes one call",
              f"- **Chunking:** none. One page per record ({len(retriever.names)} pages, standard + verified tickets); "
              f"search hits capped at {retrieval.HIT_CHARS} chars, `read_page` at {retrieval.READ_CHARS:,}",
              f"- **Embedding model:** `{retriever.embed_model}`"
              + ("" if set(techniques) & retrieval.EMBEDDING_TECHNIQUES else " (not used in this run)"),
              f"- **Embedding tokens (measured):** {retriever.page_embed_tokens:,} to embed all "
              f"{len(retriever.names)} pages once, from the provider's `usage.total_tokens`; "
              f"{retriever.embed_tokens:,} embedded by this run (queries, plus pages if not cached)",
              f"- **Hybrid:** RRF, k = {retrieval.RRF_K}, over BM25 top 20 and dense top 20",
              f"- **Pipeline:** `answer_once`, hybrid top {retrieval.ANSWER_TOP_K}, one answer call",
              "- **Scoring:** Session 5's rule, two changes. Pass = every expected term in the answer (underscores read "
              f"as spaces; a list means any one phrasing) and no decline; a decline question passes on a "
              f"`{retrieval.DECLINE_PREFIX}` line "
              "with no forbidden term. Cited = **every** gold page named in the answer (Session 5: any). "
              "Substring scoring cannot tell a confident answer from a hedged one; that needs the Week 4 judge.",
              ""]
    RESULTS.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--only", help="run one question id")
    parser.add_argument("--techniques", default=",".join([*retrieval.TECHNIQUES, retrieval.PIPELINE]))
    args = parser.parse_args()

    cases = [json.loads(line) for line in LABELS.read_text().splitlines() if line.strip()]
    if args.only:
        cases = [case for case in cases if case["id"] == args.only]
    techniques = args.techniques.split(",")
    # Fail before any paid call, not after the corpus has been embedded.
    unknown = [name for name in techniques if name not in {*retrieval.TECHNIQUES, retrieval.PIPELINE}]
    if not cases or unknown:
        parser.error(f"no question matches --only {args.only!r}" if not cases else f"unknown techniques: {unknown}")
    retriever = retrieval.Retriever(corpus.load_corpus(), cache_dir=EMBED_CACHE)
    started = datetime.now()

    # Recorded per question so the decline threshold is set from data, not picked.
    # Skipped when no selected technique embeds: BM25 and DCI need only a chat model.
    uses_embeddings = bool(set(techniques) & retrieval.EMBEDDING_TECHNIQUES)
    similarities = {case["id"]: retriever.top_similarity(case["question"]) if uses_embeddings else None
                    for case in cases}

    rows = []
    # A debug run gets its own file, so it never overwrites the traces behind the report.
    traces_path = TRACES.with_name(f"retrieval_traces_{args.only}.jsonl") if args.only else TRACES
    traces_path.parent.mkdir(parents=True, exist_ok=True)
    with traces_path.open("w", encoding="utf-8") as traces:
        for case in cases:
            for technique in techniques:
                clock = time.perf_counter()
                result = retrieval.ask(case["question"], technique, retriever)
                row = {"id": case["id"], "technique": technique, **score(case, result, retriever)}
                rows.append(row)
                traces.write(json.dumps({**row, "answer": result["answer"], "trace": result["trace"]}) + "\n")
                print(f"{case['id']} {technique:16} pass={row['pass']!s:5} cited={row['cited']!s:5} "
                      f"calls={row['calls']} {time.perf_counter() - clock:.1f}s", flush=True)

    table = summarise(rows, techniques)
    if not args.only:
        write_report(table, rows, cases, similarities, retriever, started, techniques)
    for row in table:
        print(row)
    print("embedding tokens (measured):", retriever.embed_tokens)


if __name__ == "__main__":
    main()
